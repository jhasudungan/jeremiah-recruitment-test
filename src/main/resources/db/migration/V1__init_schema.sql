-- V1: tables, constraints and indexes
-- Balance is BIGINT in the smallest unit (Rp1). Timestamps are TIMESTAMPTZ.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_users_username UNIQUE (username)
);

CREATE TABLE account (
    number          BIGINT       PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    full_name       VARCHAR(255) NOT NULL,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    balance         BIGINT       NOT NULL DEFAULT 0,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_updated    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_account_user    FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_account_balance CHECK (balance >= 0)
);

CREATE TABLE balance_transfer (
    reference_number            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key             VARCHAR(64)  NOT NULL,
    originator_account_number   BIGINT       NOT NULL,
    beneficiary_account_number  BIGINT       NOT NULL,
    amount                      BIGINT       NOT NULL,
    status                      VARCHAR(20)  NOT NULL DEFAULT 'SUCCESS',
    remark                      VARCHAR(255),
    transferred_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_transfer_originator  FOREIGN KEY (originator_account_number)  REFERENCES account (number),
    CONSTRAINT fk_transfer_beneficiary FOREIGN KEY (beneficiary_account_number) REFERENCES account (number),
    CONSTRAINT ck_transfer_amount      CHECK (amount > 0),
    CONSTRAINT ck_transfer_not_self    CHECK (originator_account_number <> beneficiary_account_number),
    CONSTRAINT ck_transfer_status      CHECK (status IN ('SUCCESS', 'FAILED')),
    CONSTRAINT uq_transfer_idempotency UNIQUE (originator_account_number, idempotency_key)
);

CREATE TABLE ledger (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number              BIGINT      NOT NULL,
    transfer_reference_number   BIGINT      NOT NULL,
    entry_type                  VARCHAR(6)  NOT NULL,
    amount                      BIGINT      NOT NULL,
    balance_after               BIGINT      NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_ledger_account       FOREIGN KEY (account_number)            REFERENCES account (number),
    CONSTRAINT fk_ledger_transfer      FOREIGN KEY (transfer_reference_number) REFERENCES balance_transfer (reference_number),
    CONSTRAINT ck_ledger_type          CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_amount        CHECK (amount > 0),
    CONSTRAINT ck_ledger_balance       CHECK (balance_after >= 0),
    CONSTRAINT uq_ledger_transfer_type UNIQUE (transfer_reference_number, entry_type)
);

-- Postgres does not index foreign keys automatically
CREATE INDEX idx_account_user_id           ON account (user_id);
CREATE INDEX idx_transfer_originator_time  ON balance_transfer (originator_account_number, transferred_at DESC);
CREATE INDEX idx_transfer_beneficiary_time ON balance_transfer (beneficiary_account_number, transferred_at DESC);
CREATE INDEX idx_ledger_account_time       ON ledger (account_number, created_at DESC);